"""Rewrite the "Current resources" table in README.md from a catalog database.

An icon is one drawing; its images are colour and style variants of it, counted once (see ICON_KEY).
App uploads (source `user`) and every template are listed as BioCartoon, which always comes
first; every source is shown by its full name and links to where it comes from. Licenses come from the rows themselves.

    python data/readme_stats.py                                   # from data/catalog/*.sqlite.gz
    python data/readme_stats.py --db data/assets.sqlite

publish_catalog.py calls `update()` on every catalog it builds, so the README follows the catalog.
The table lives between the README_START / README_END markers; everything else is left alone.
The same run writes the table between the APP_START / APP_END markers in the editor's README (the
biocartoon-app checkout next to this one), when it is there.
"""
