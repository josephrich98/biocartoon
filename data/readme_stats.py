def license_label(counts: Counter) -> str:
    """'CC-BY-4.0' x3, 'CC-BY-3.0' x1, 'MIT' x1 -> 'CC BY / MIT' (version kept when only one is used)."""
    fams: dict[str, Counter] = defaultdict(Counter)
    for lic, n in counts.items():
        m = re.fullmatch(r"(CC-BY-SA|CC-BY|CC0)-(\d\.\d)", lic)
        fam, ver = (m.group(1), m.group(2)) if m else (lic, None)
        fams[fam][ver] += n
    out = []
    for fam, vers in sorted(fams.items(), key=lambda kv: -sum(kv[1].values())):
        name = FAMILIES.get(fam, fam)
        ver = next(iter(vers)) if len(vers) == 1 else None
        out.append(f"{name} {ver}" if ver and fam != "CC0" else name)
    return " / ".join(out)


def stats(db: Path, templates: int = 0) -> list[tuple[str, int, int, str]]:
    con = sqlite3.connect(f"file:{db}?mode=ro", uri=True)
    icons = dict(con.execute(f"SELECT source, count(DISTINCT {ICON_KEY}) FROM assets WHERE png_key IS NOT NULL GROUP BY source"))
    lics: dict[str, Counter] = defaultdict(Counter)
    for src, lic, n in con.execute("SELECT source, license, count(*) FROM assets WHERE png_key IS NOT NULL GROUP BY 1, 2"):
        lics[src][lic] = n
    con.close()
    icons.setdefault("user", 0)
    rows = [(s, n, templates if s == "user" else 0, license_label(lics[s])) for s, n in icons.items()]
    # Our own icons and templates first, then the upstream collections alphabetically.
    return sorted(rows, key=lambda r: (r[0] != "user", source_name(r[0]).lower()))


def source_name(source: str) -> str:
    return DISPLAY.get(source, (source, None))[0]


def source_cell(source: str) -> str:
    """'servier' -> '[Servier Medical Art](https://smart.servier.com)'; the bare id when unknown."""
    name, url = DISPLAY.get(source, (source, None))
    return f"[{name}]({url})" if url else name


def count_templates(db: Path | None) -> int:
    if db is None or not db.exists():
        return 0
    con = sqlite3.connect(f"file:{db}?mode=ro", uri=True)
    n = con.execute("SELECT count(*) FROM templates").fetchone()[0]
    con.close()
    return n


def examples_cell(source: str) -> str:
    return " ".join(f'<img src="{ASSETS_URL}{key}" alt="{label}" title="{label}" height="32">'
                    for key, label in EXAMPLES.get(source, []))


def example_credits(db: Path) -> list[str]:
    """The `credit` of every example icon, in table order; one missing from the catalog is a warning."""
    keys = [key for _, examples in sorted(EXAMPLES.items(), key=lambda kv: source_name(kv[0]).lower())
            for key, _ in examples]
    con = sqlite3.connect(f"file:{db}?mode=ro", uri=True)
    credits = dict(con.execute(f"SELECT png_key, credit FROM assets WHERE png_key IN ({','.join('?' * len(keys))})", keys))
    con.close()
    for key in keys:
        if key not in credits:
            print(f"warning: example icon {key} is not in the catalog; not credited")
    return [credits[k] for k in keys if k in credits]


def render(rows: list[tuple[str, int, int, str]], credits: list[str] = ()) -> str:
    icons, templates = sum(r[1] for r in rows), sum(r[2] for r in rows)
    lines = [f"{icons:,} icons and {templates:,} templates across {len(rows)} resources.", "",
             "| source | icons | license | examples |", "|---|---|---|---|"]
    lines += [f"| {source_cell(s)} | {n:,} | {lic} | {examples_cell(s)} |" for s, n, _, lic in rows]
    if credits:
        lines += ["", "<details><summary>Example icon credits</summary>", ""]
        lines += [f"- {c}" for c in credits]
        lines += ["", "</details>"]
    return "\n".join(lines)


def replace_block(path: Path, start: str, end: str, body: str, what: str) -> bool:
    """Put `body` between the `start` and `end` markers in `path`. False (and the file untouched)
    when the markers are missing."""
    text = path.read_text()
    i, j = text.find(start), text.find(end)
    if i < 0 or j < i:
        print(f"warning: {path} has no {start} ... {end} block; not updated")
        return False
    new = text[: i + len(start)] + body + text[j:]
    if new != text:
        path.write_text(new)
        print(f"updated the {what} in {path}")
    return True


def update(db: Path, readme: Path = README, templates_db: Path | None = None,
           app_readme: Path = APP_README) -> bool:
    """Rewrite the marked block in `readme`, and in `app_readme` when that file exists."""
    table = "\n" + render(stats(db, count_templates(templates_db)), example_credits(db)) + "\n"
    ok = replace_block(readme, README_START, README_END, table, "resources table")
    if app_readme.exists():
        replace_block(app_readme, APP_START, APP_END, table, "resources table")
    return ok


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--db", default=str(DATA / "catalog" / "assets.sqlite.gz"), help=".sqlite or .sqlite.gz")
    ap.add_argument("--templates-db", default=str(DATA / "catalog" / "templates.sqlite.gz"), help=".sqlite or .sqlite.gz")
    ap.add_argument("--readme", default=str(README))
    a = ap.parse_args()
    with tempfile.TemporaryDirectory() as tmp:
        def unpack(db: Path) -> Path:
            if db.suffix != ".gz" or not db.exists():
                return db
            out = Path(tmp) / db.stem
            with gzip.open(db, "rb") as f, open(out, "wb") as g:
                shutil.copyfileobj(f, g)
            return out
        ok = update(unpack(Path(a.db)), Path(a.readme), unpack(Path(a.templates_db)))
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
